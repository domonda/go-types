// Package country provides ISO 3166-1 alpha-2 country codes.
//
// [Code] is a string type with a constant for every ISO 3166-1 alpha-2
// code ([DE], [AT], ...) plus [EL], the EU's code for Greece used in
// VAT IDs, and [XK] for Kosovo. [Code.Normalized] accepts lower case,
// surrounding whitespace and the alternative codes and German country
// names of [AltCodes] ("d", "SUI", "Österreich"). [ParseCode] also
// accepts English country names ("Germany").
//
// The package includes:
//   - [Code] and [NullableCode]; an empty string is SQL NULL and
//     a null [NullableCode] is JSON null
//   - EU membership with [Code.IsEU] and English names with [Code.EnglishName]
//   - [Code.Enums] and [Code.EnumStrings], generated by go-enum,
//     to list all codes
//
// [Code.Valid] and [Code.Validate] normalize first, so "de" is valid.
// Scan, JSON and XML decoding store a valid code normalized and an invalid
// one unchanged, SQL Value and JSON output are normalized ("de" is written
// as "DE"), Value returns an error for an invalid code, and fmt prints the
// code as stored.
//
// See the README.md of this package for the full API
// and how to add a country code.
package country
