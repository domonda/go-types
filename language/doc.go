// Package language provides ISO 639-1 two-letter language codes.
//
// [Code] is a string type with a constant for every ISO 639-1 code
// ([EN], [DE], ...). [Code.Normalized] maps other identifiers to
// ISO 639-1: upper case, ISO 639-2/T and 639-2/B codes ("deu", "ger"),
// ISO 639-3 codes that have an ISO 639-1 equivalent, BCP-47 tags and
// POSIX locales ("en-US", "zh_Hant"). [ParseCode] also accepts English
// language names ("German").
//
// [Code.Valid] and [Code.Validate] normalize first and accept every
// spelling that [Code.Normalized] accepts. Reading and [Code.Value] only
// trim, so "EN" stays "EN". Call [Code.Normalized] for the ISO 639-1 code.
// [Code.ValidAndNormalized]
// only accepts a canonical lower-case code.
//
// The package includes:
//   - [Code] with SQL Scan and Value methods, where [Null] is SQL NULL
//   - English names with [Code.LanguageName]
//   - [Code.Enums] and [Code.EnumStrings], generated by go-enum,
//     to list all codes
//   - [ISO6393Name] and [ISO6393Macrolanguage] for the full ISO 639-3
//     tables, generated by the gen-lang-maps command
//
// See the README.md of this package for the full API
// and how to add a language code.
package language
